// Run existing acceptance scripts against mocked data. Never contacts a controller.
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const options = {};
for (let i = 0; i < args.length; i += 2) {
  if (!['--blank', '--browser', '--playwright'].includes(args[i]) || !args[i + 1]) {
    console.error('Usage: npm run test:browser -- --blank PATH [--browser PATH] [--playwright PATH]');
    process.exit(1);
  }
  options[args[i]] = path.resolve(args[i + 1]);
}
if (!options['--blank'] || !fs.existsSync(options['--blank'])) {
  console.error('Provide a blank fixture generated by tests/controller/run_tests.py --blank-output PATH');
  process.exit(1);
}
const suites = [
  'check_ui.cjs', 'check_automation_ui.cjs', 'check_backup_ui.cjs',
  'check_diagnostics_ui.cjs', 'check_events_ui.cjs', 'check_fan_ui.cjs',
  'check_history_ui.cjs', 'check_schedule_ui.cjs',
];
const forwarded = Object.entries(options).flat();
for (const suite of suites) {
  console.log(`\nBrowser suite: ${suite}`);
  const result = spawnSync(process.execPath,
    [path.join(root, 'tests/controller', suite), ...forwarded],
    { cwd: root, stdio: 'inherit' });
  if (result.error) console.error(result.error.message);
  if (result.status !== 0) process.exit(result.status || 1);
}
console.log(`\nAll ${suites.length} browser suites passed.`);
